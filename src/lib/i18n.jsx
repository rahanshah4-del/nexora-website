const LANGUAGE_ALIASES = LANGUAGE_OPTIONS.reduce((aliases, option) => {
  aliases[option.code.toLowerCase()] = option.code
  aliases[option.label.toLowerCase()] = option.code
  aliases[option.nativeName.toLowerCase()] = option.code
  return aliases
}, {})

export function normalizeLanguage(value) {
  const key = String(value || '').trim().toLowerCase()
  return LANGUAGE_ALIASES[key] || 'en'
}

export function languageMeta(value) {
  const code = normalizeLanguage(value)
  return LANGUAGE_OPTIONS.find((option) => option.code === code) || LANGUAGE_OPTIONS[0]
}

export function languageLabel(value) {
  const meta = languageMeta(value)
  return meta.label
}

