export function tx(key, language = 'en', fallback = '') {
  const code = normalizeLanguage(language)
  return DICTIONARY[code]?.[key] || DICTIONARY.en[key] || fallback || key
}

const LanguageContext = createContext({
  language: 'en',
  meta: LANGUAGE_OPTIONS[0],
  setLanguage: () => {},
  t: (key, fallback) => tx(key, 'en', fallback),
})

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    if (typeof window === 'undefined') return 'en'
    try {
      return normalizeLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY) || 'en')
    } catch {
      return 'en'
    }
  })

  const setLanguage = useCallback((nextLanguage) => {
    const next = normalizeLanguage(nextLanguage)
    setLanguageState(next)
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next)
    } catch {
      // Ignore storage failures.
    }
  }, [])

  const meta = useMemo(() => languageMeta(language), [language])

  useEffect(() => {
    if (typeof document === 'undefined') return
    const root = document.documentElement
    root.lang = meta.htmlLang
    root.dir = meta.dir
    root.dataset.language = meta.code
    root.style.setProperty('--nexora-language-font', meta.fontFamily)
  }, [meta])

  const t = useCallback((key, fallback = '') => tx(key, language, fallback), [language])

  const value = useMemo(() => ({ language, meta, setLanguage, t }), [language, meta, setLanguage, t])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  return useContext(LanguageContext)
}
