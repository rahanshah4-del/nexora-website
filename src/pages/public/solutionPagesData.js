/* Shared content for solution pages that have their own dedicated layout
   (CRM, Restaurant POS, Retail POS). One source of truth for copy, FAQs and
   links, so headings and schema never drift between layouts. */
export function getSolutionPageData(solutionSlug) {
  const page = solutionPages[solutionSlug]
  const pillarKey = SOLUTION_SLUG_TO_PILLAR[solutionSlug]
  return {
    page,
    seo: getSeoForSolutionSlug(solutionSlug),
    faqs: page.ownFaqsOnly ? page.faqs : [...page.faqs, ...commonFaqs],
    relatedSolutions: getRelatedSolutions(solutionSlug),
    supportingPages: pillarKey
      ? Object.entries(featurePages).filter(([, fp]) => fp.pillar === pillarKey).map(([key, fp]) => ({ key, ...fp }))
      : [],
    compareLinks: pillarKey ? (PILLAR_COMPARE_LINKS[pillarKey] || []) : [],
  }
}
