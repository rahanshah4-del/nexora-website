/** localStorage key — tracks whether demo has been loaded already */
export const DEMO_MENU_LOADED_KEY = 'nexora.restaurant.menu.demo_loaded.v1'

export function hasDemoMenuLoaded() {
  if (typeof window === 'undefined') return false
  try {
    return window.localStorage.getItem(DEMO_MENU_LOADED_KEY) === 'true'
  } catch {
    return false
  }
}

export function markDemoMenuLoaded() {
  if (typeof window === 'undefined') return
  try {
    window.localStorage.setItem(DEMO_MENU_LOADED_KEY, 'true')
  } catch { /* noop */ }
}

/** Check if any items in the array are NOT demo items (user-created) */
export function hasUserCreatedItems(items = []) {
  return items.some((item) => !String(item.id || '').startsWith('demo-'))
}

/** Remove all demo items from an array */
export function removeDemoItems(items = []) {
  return items.filter((item) => !String(item.id || '').startsWith('demo-'))
}
