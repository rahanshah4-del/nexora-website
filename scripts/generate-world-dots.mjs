/**
 * Builds src/lib/worldDots.js: land of the world as an equal-spacing grid of dots, each tagged with the
 * market (country) it belongs to when that country is one of the wizard's markets.
 *
 * Run (the packages are only needed for this one-off build, so they are not project dependencies):
 *   npm i --no-save world-atlas@2 topojson-client@3 d3-geo@3
 *   node scripts/generate-world-dots.mjs > src/lib/worldDots.js
 */
import { createRequire } from 'node:module'
import { geoContains } from 'd3-geo'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const land = feature(require('world-atlas/land-50m.json'), require('world-atlas/land-50m.json').objects.land)
const countriesTopo = require('world-atlas/countries-50m.json')
const countries = feature(countriesTopo, countriesTopo.objects.countries).features

// name used by the wizard -> [name in the map data, centre lat, centre lon, radius in degrees that still counts as that country]
const MARKETS = [
  ['United States', 'United States of America', 39, -98, 62], ['United Kingdom', 'United Kingdom', 54, -2, 8], ['Canada', 'Canada', 56, -96, 45],
  ['Australia', 'Australia', -25, 134, 40], ['Pakistan', 'Pakistan', 30, 70, 14], ['India', 'India', 22, 79, 22],
  ['United Arab Emirates', 'United Arab Emirates', 24, 54, 5], ['Saudi Arabia', 'Saudi Arabia', 24, 45, 14], ['Bahrain', 'Bahrain', 26, 50.5, 2],
  ['Qatar', 'Qatar', 25.3, 51.2, 3], ['Germany', 'Germany', 51, 10, 7], ['France', 'France', 46.6, 2.3, 9], ['Spain', 'Spain', 40, -3.7, 9],
  ['Italy', 'Italy', 42.8, 12.5, 9], ['Netherlands', 'Netherlands', 52.2, 5.3, 3], ['Turkey', 'Turkey', 39, 35, 12], ['Nigeria', 'Nigeria', 9, 8, 8],
  ['South Africa', 'South Africa', -29, 24, 12], ['Singapore', 'Singapore', 1.35, 103.8, 2], ['Malaysia', 'Malaysia', 4, 102, 10], ['Indonesia', 'Indonesia', -2, 118, 24],
]
const rad = Math.PI / 180
const distance = (la1, lo1, la2, lo2) => Math.acos(Math.min(1, Math.max(-1, Math.sin(la1 * rad) * Math.sin(la2 * rad) + Math.cos(la1 * rad) * Math.cos(la2 * rad) * Math.cos((lo1 - lo2) * rad)))) / rad

const shapes = MARKETS.map(([, source]) => countries.filter((c) => c.properties.name === source || (source === 'Turkey' && c.properties.name === 'Türkiye')))
shapes.forEach((s, i) => { if (!s.length) console.error('not in map data:', MARKETS[i][0]) })

const STEP = 2.1
const dots = []
for (let lat = -84; lat <= 84; lat += STEP) {
  const n = Math.max(1, Math.round((360 * Math.cos(lat * rad)) / STEP))
  for (let i = 0; i < n; i += 1) {
    const lon = -180 + ((i + 0.5) * 360) / n
    if (!geoContains(land, [lon, lat])) continue
    let id = 0
    for (let m = 0; m < MARKETS.length && !id; m += 1) {
      const [, , clat, clon, r] = MARKETS[m]
      if (distance(lat, lon, clat, clon) <= r && shapes[m].some((s) => geoContains(s, [lon, lat]))) id = m + 1
    }
    dots.push(Math.round(lat * 10), Math.round(lon * 10), id)
  }
}
console.error('dots', dots.length / 3)
const centres = Object.fromEntries(MARKETS.map(([name, , lat, lon], i) => [name, { id: i + 1, lat, lon }]))
console.log(`/* Generated by scripts/generate-world-dots.mjs from Natural Earth land (world-atlas, public domain). Do not edit by hand.
   WORLD_DOTS is flat: latitude x10, longitude x10, market id (0 = not one of the wizard's markets), repeated. */
export const MARKET_GEO = ${JSON.stringify(centres)}
export const WORLD_DOTS = [${dots.join(',')}]
`)
